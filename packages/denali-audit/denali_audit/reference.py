def percentile(r2: float) -> float:
    """Share of published screens LESS size-confounded than this one, 0-100."""
    return round(100.0 * bisect.bisect_left(CORPUS, float(r2)) / len(CORPUS), 1)


def context(r2: float) -> dict:
    """Where this ranking sits against the published literature."""
    p = percentile(r2)
    if p >= 90:
        band = ("unusually confounded -- worse than nine in ten published screens")
    elif p >= 75:
        band = "more confounded than most published screens"
    elif p >= 40:
        band = "typical of published screens"
    else:
        band = "less confounded than most published screens"
    return {
        "corpus_percentile": p,
        "corpus_n_screens": N_SCREENS,
        "corpus_collection": COLLECTION,
        "corpus_reading": (
            f"This ranking is {band}: {p:.0f}% of {N_SCREENS} published CRISPR "
            f"screens are less explained by set size than yours."),
        "corpus_caveat": (
            "The reference was built against " + COLLECTION + ". If your sets came "
            "from a different collection the percentile is indicative, not exact."),
        "corpus_source": SOURCE,
    }
